#!/usr/bin/env bash
# Concatenates every migration in supabase/migrations/, in order, into one
# paste-ready SQL file — for bootstrapping a brand-new Supabase project
# (e.g. a staging environment) in one shot instead of running 24+ files
# one at a time through the SQL Editor. Always reads the current migration
# list, so it never goes stale as new migrations are added.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="${1:-bootstrap.sql}"

{
  echo "-- Generated by scripts/build-bootstrap-sql.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "-- Paste this whole file into a NEW Supabase project's SQL Editor and run it once."
  echo
  for f in supabase/migrations/*.sql; do
    echo "-- ───────────────────────────────────────────────────────────"
    echo "-- $(basename "$f")"
    echo "-- ───────────────────────────────────────────────────────────"
    cat "$f"
    echo
  done
} > "$OUT"

echo "Wrote $(ls supabase/migrations/*.sql | wc -l | tr -d ' ') migrations to $OUT"
